import assert from 'node:assert/strict'
import { readFileSync } from 'node:fs'
const read = path => readFileSync(new URL(`../${path}`, import.meta.url), 'utf8')
const hosted = read('src/renderer/src/hosted-session-ux.ts')
const unified = read('src/renderer/src/unified-session-ux.ts')
const types = read('src/main/hosted-signaling-bridge.d.mts')
assert.match(types, /join\(code: string, displayName: string\)/, 'bridge declaration needs two join parameters')
assert.match(types, /guestDisplayName: string \| null/, 'host-only guest name snapshot declaration')
assert.match(hosted, /codeField\.addEventListener\('click'/)
assert.match(hosted, /codeField\.select\(\)/)
assert.match(hosted, /event\.stopPropagation\(\)/)
assert.match(hosted, /join: \(code: string, name: string\) => window\.captureLink\.hostedJoin\(code, name\)/)
assert.match(hosted, /await selectedBackend\.join\(code, name\)/)
assert.match(hosted, /Only dismiss the guest name prompt after the broker accepted the join/)
assert.match(hosted, /nameError\.textContent = message/)
assert.match(hosted, /nameInput\.focus\(\)/)
assert.match(hosted, /guestJoinPending/)
assert.match(hosted, /end: \(\) => window\.captureLink\.hostedEnd\(\)/)
assert.match(hosted, /await failedBackend\?\.end\(\)/)
assert.doesNotMatch(unified, /if \(event\.target === overlay\) close\(\)/, 'backdrop must not accidentally dismiss drawer')
assert.match(unified, /closeButton\.addEventListener\('click', close\)/)
assert.match(unified, /if \(confirmDialog\.open \|\| overlay\.hidden\) return/)
console.log('PASS: guest retry, invitation selection, no accidental drawer dismissal, bridge types, explicit close')
