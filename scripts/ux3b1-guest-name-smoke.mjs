import assert from 'node:assert/strict'
import { readFileSync } from 'node:fs'
const read = path => readFileSync(new URL(`../${path}`, import.meta.url), 'utf8')
const ui = read('src/renderer/src/hosted-session-ux.ts')
const css = read('src/renderer/src/styles.css')
const main = read('src/main/index.ts')
const preload = read('src/preload/index.ts')
const env = read('src/renderer/src/env.d.ts')
const bridge = read('src/main/hosted-signaling-bridge.mjs')
const server = read('services/signaling/src/server.mjs')
for (const token of ['clux3-name-dialog', 'clux3-name-form', 'clux3-guest-name', 'clux3-requester', 'clux3-name-cancel']) {
  assert.ok(ui.includes(token), 'Missing UI element ' + token)
}
assert.match(ui, /nameDialog\.showModal\(\)/)
assert.match(ui, /hostedJoin\(code, name\)/)
assert.match(ui, /requester\.textContent = snap\.guestDisplayName/)
assert.doesNotMatch(ui, /requester\.innerHTML/)
assert.match(ui, /name was entered by the guest and has NOT been verified/)
assert.match(ui, /nameDialog\.close\(\)/)
assert.match(ui, /nameInput\.value = ''/)
assert.match(css, /\.clux3-name-dialog::backdrop/)
assert.match(main, /hostedSignaling\.join\(code, displayName\)/)
assert.match(preload, /ipcRenderer\.invoke\('capturelink:hosted-join', code, displayName\)/)
assert.match(env, /hostedJoin\(code: string, displayName: string\)/)
assert.match(env, /guestDisplayName: string \| null/)
assert.match(bridge, /canonicalGuestName\(displayName\)/)
assert.match(server, /role === 'host' && session\.guest/)
assert.match(server, /displayName: guestDisplayName/)
console.log('PASS: UX3b1 guest name prompt, unverified host label, strict IPC, host-only broker data, cleanup')
