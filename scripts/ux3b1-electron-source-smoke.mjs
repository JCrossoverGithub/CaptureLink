import assert from 'node:assert/strict'
import { readFileSync } from 'node:fs'
const root = new URL('../', import.meta.url)
const read = path => readFileSync(new URL(path, root), 'utf8')
const main = read('src/main/index.ts')
const preload = read('src/preload/index.ts')
const types = read('src/renderer/src/env.d.ts')
const ui = read('src/renderer/src/hosted-session-ux.ts')
const older = read('src/renderer/src/unified-session-ux.ts')
for (const method of ['create', 'join', 'snapshot', 'approve', 'send', 'messages', 'end']) {
  assert.match(main, new RegExp(`capturelink:hosted-${method}`))
  assert.match(preload, new RegExp(`capturelink:hosted-${method}`))
  assert.match(types, new RegExp(`hosted${method.charAt(0).toUpperCase()+method.slice(1)}\\(`))
}
assert.match(main, /authorizedHostedFrame\(event\)/)
assert.match(main, /event\.senderFrame !== mainWindow\.webContents\.mainFrame/)
assert.match(main, /pathToFileURL/)
assert.match(ui, /Host approved/)
assert.match(ui, /name was entered by the guest and has NOT been verified/)
assert.match(ui, /clux3-name-dialog/)
assert.match(ui, /nameDialog\.showModal\(\)/)
assert.match(ui, /hostedJoin\(code, name\)/)
assert.match(ui, /requester\.textContent = snap\.guestDisplayName/)
assert.doesNotMatch(ui, /requester\.innerHTML/)
assert.match(ui, /guestMicConsent/)
assert.match(ui, /coordinator\.joinInvitation\(wire, guestMicConsent\)/)
assert.match(ui, /coordinator\.acceptResponse\(answer\.payload\)/)
assert.match(ui, /manual\.append\(manualFlow\)/)
assert.match(older, /installHostedSessionUx/)
assert.match(older, /#clux2-create-invite/)
assert.match(older, /#clux2-join-invite/)
console.log('PASS: UX3b1 guarded main/preload IPC, explicit approval, consent, and preserved UX2 fallback')
