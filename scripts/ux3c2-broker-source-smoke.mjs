// Dependency-free source contract; cannot substitute for live broker tests.
import assert from 'node:assert/strict'
import { readFileSync } from 'node:fs'
const source = file => readFileSync(new URL(file, import.meta.url), 'utf8').replace(/\r\n/g, '\n')
const broker = source('../services/signaling/src/server.mjs')
const admission = source('../services/signaling/src/pilot-admission.mjs')
const client = source('../services/signaling/src/client.mjs')
const selector = source('../src/main/ux3c-signaling-client.mjs')
const main = source('../src/main/index.ts')
const ci = source('../.github/workflows/ci.yml')
const need = (value, pattern, name) => assert.match(value, pattern, name)
need(broker, /export function createSignalingServer\(\{ now = Date\.now, allowedOrigins = \[\], maxSessions = MAX_SESSIONS, pilot = null \}/, 'local factory defaults remain independent')
need(broker, /export function createPilotSignalingServer\(/, 'separate pilot factory')
need(broker, /server\.listen\(port, '127\.0\.0\.1'/, 'loopback bind invariant')
need(broker, /forwarded_headers_forbidden/, 'reject untrusted forwarding metadata')
need(broker, /installationId !== \(role === 'host' \? session\.hostInstallationId : session\.guest\?\.installationId\)/, 'installation/role binding')
need(broker, /ensureCurrentAdmission\(installationId, session\)/, 're-check admission after async body')
need(broker, /revokeInstallation\(installationId\)/, 'operator revocation')
need(admission, /createHash\('sha256'\)/, 'tokens hashed in registry')
need(admission, /activePerInstallation: 4/, 'per-install capacity')
need(client, /class RemoteSignalingClient/, 'remote client still separate')
need(selector, /mode = 'local'/, 'main selector local default')
need(main, /createSignalingClientForMain\(\)/, 'shipping desktop still uses local client')
need(ci, /UX3c-2 pilot broker admission and abuse tests/, 'CI includes pilot tests')
assert.doesNotMatch(broker, /server\.listen\(port, ['"]0\.0\.0\.0['"]/, 'no all-interface listener')
assert.doesNotMatch(broker, /process\.env\.CAPTURELINK_PILOT_/, 'no environment-driven public pilot toggle')
console.log('PASS: localhost default, pilot admission and quotas, loopback-only listener, trusted main selector, CI gates')
